object Motion { const val SHORT = 120; const val SCREEN = 280; const val COLOR = 400; const val PROGRESS = 500 }
val LocalReducedMotion = staticCompositionLocalOf { false }
private val cache = java.util.concurrent.ConcurrentHashMap<Pair<Long, Boolean>, ColorScheme>()
@SuppressLint("RestrictedApi")
fun seedScheme(seed: Long, dark: Boolean): ColorScheme = cache.getOrPut(seed to dark) {
    val hct = Hct.fromInt(seed.toInt())
    val p = TonalPalette.fromHueAndChroma(hct.hue, 36.0)
    val s = TonalPalette.fromHueAndChroma(hct.hue, 16.0)
    val t = TonalPalette.fromHueAndChroma((hct.hue + 60) % 360, 24.0)
    val n = TonalPalette.fromHueAndChroma(hct.hue, 6.0)
    val v = TonalPalette.fromHueAndChroma(hct.hue, 8.0)
    fun color(pal: TonalPalette, light: Int, night: Int) = Color(pal.tone(if (dark) night else light))
    val base = if (dark) darkColorScheme() else lightColorScheme()
    base.copy(
        primary=color(p,40,80), onPrimary=color(p,100,20), primaryContainer=color(p,90,30), onPrimaryContainer=color(p,10,90), inversePrimary=color(p,80,40),
        secondary=color(s,40,80), onSecondary=color(s,100,20), secondaryContainer=color(s,90,30), onSecondaryContainer=color(s,10,90),
        tertiary=color(t,40,80), onTertiary=color(t,100,20), tertiaryContainer=color(t,90,30), onTertiaryContainer=color(t,10,90),
        background=color(n,98,6), onBackground=color(n,10,90), surface=color(n,98,6), onSurface=color(n,10,90),
        surfaceVariant=color(v,90,30), onSurfaceVariant=color(v,30,80), outline=color(v,50,60), outlineVariant=color(v,80,30),
        inverseSurface=color(n,20,90), inverseOnSurface=color(n,95,20), surfaceTint=color(p,40,80),
        surfaceBright=color(n,98,24), surfaceDim=color(n,87,6), surfaceContainerLowest=color(n,100,4),
        surfaceContainerLow=color(n,96,10), surfaceContainer=color(n,94,12), surfaceContainerHigh=color(n,92,17), surfaceContainerHighest=color(n,90,22))
}
@Composable
fun AppTheme(settings: ThemeSettings, content: @Composable () -> Unit) {
    val dark = when(settings.theme) { "dark" -> true; "light" -> false; else -> isSystemInDarkTheme() }
    val context = LocalContext.current
    val seed = if(settings.palette == "custom") settings.seed else 0xFF146B55
    val generated by produceState(if(dark) darkColorScheme() else lightColorScheme(), seed, dark) { value = withContext(Dispatchers.Default) { seedScheme(seed, dark) } }
    val target = if(settings.palette == "dynamic" && Build.VERSION.SDK_INT >= 31) { if(dark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context) } else generated
    val duration = if(settings.reducedMotion) Motion.SHORT else Motion.COLOR
    @Composable fun c(value: Color) = animateColorAsState(value, tween(duration), label="theme").value
    val animated = target.copy(primary=c(target.primary), onPrimary=c(target.onPrimary), primaryContainer=c(target.primaryContainer), onPrimaryContainer=c(target.onPrimaryContainer),
        secondary=c(target.secondary), onSecondary=c(target.onSecondary), secondaryContainer=c(target.secondaryContainer), onSecondaryContainer=c(target.onSecondaryContainer),
        tertiary=c(target.tertiary), onTertiary=c(target.onTertiary), tertiaryContainer=c(target.tertiaryContainer), onTertiaryContainer=c(target.onTertiaryContainer),
        background=c(target.background), onBackground=c(target.onBackground), surface=c(target.surface), onSurface=c(target.onSurface), surfaceVariant=c(target.surfaceVariant), onSurfaceVariant=c(target.onSurfaceVariant),
        outline=c(target.outline), outlineVariant=c(target.outlineVariant), inverseSurface=c(target.inverseSurface), inverseOnSurface=c(target.inverseOnSurface), inversePrimary=c(target.inversePrimary), surfaceTint=c(target.surfaceTint),
        surfaceBright=c(target.surfaceBright), surfaceDim=c(target.surfaceDim), surfaceContainerLowest=c(target.surfaceContainerLowest), surfaceContainerLow=c(target.surfaceContainerLow), surfaceContainer=c(target.surfaceContainer), surfaceContainerHigh=c(target.surfaceContainerHigh), surfaceContainerHighest=c(target.surfaceContainerHighest))
    SideEffect {
        (context as? android.app.Activity)?.window?.let { window ->
            WindowCompat.getInsetsController(window, window.decorView).apply {
                isAppearanceLightStatusBars = animated.surface.luminance() > 0.5f
                isAppearanceLightNavigationBars = animated.surface.luminance() > 0.5f
            }
        }
    }
    CompositionLocalProvider(LocalReducedMotion provides settings.reducedMotion) { MaterialTheme(colorScheme=animated, content=content) }
}
